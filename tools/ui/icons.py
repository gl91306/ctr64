def rle(vals):
    out, i = [], 0
    while i < len(vals):
        j = i
        while j < len(vals) and j - i < 128 and vals[j] == vals[i]:
            j += 1
        if j - i >= 3:
            out += [0x80 | (j - i - 1), vals[i]]
            i = j
            continue
        k, lit = i, []
        while k < len(vals) and len(lit) < 128:
            if k + 2 < len(vals) and vals[k] == vals[k + 1] == vals[k + 2]:
                break
            lit.append(vals[k])
            k += 1
        out += [len(lit) - 1] + lit
        i = k
    return out


def main():
    tmp = tempfile.mkdtemp()
    masks = {}
    for name, (px, body) in ICONS.items():
        svg = os.path.join(tmp, name + '.svg')
        png = os.path.join(tmp, name + '.png')
        with open(svg, 'w') as f:
            f.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="0 0 24 24">{body}</svg>')
        subprocess.run([RSVG, '-w', str(px), '-h', str(px), '-o', png, svg], check=True)
        im = Image.open(png).convert('RGBA')
        masks[name] = (px, [round(a * 32 / 255) for (_, _, _, a) in im.getdata()])
    out = os.path.join(ROOT, 'ctr64', 'src', 'ui', 'icons_img.h')
    total = 0
    with open(out, 'w', newline='\n') as f:
        f.write('/* generated by tools/ui/icons.py; do not edit */\n#pragma once\n#include "ui.h"\n\n')
        for name, (px, vals) in masks.items():
            r = rle(vals)
            total += len(r)
            f.write(f'static const u8 k_icon_{name}_rle[{len(r)}] = {{' + ', '.join(map(str, r)) + '};\n')
            f.write(f'static const UiMask k_icon_{name} = {{{px}, {px}, k_icon_{name}_rle}};\n')
    # preview: each icon white on a coloured square, 4x
    n = len(masks)
    sheet = Image.new('RGB', (n * 30 * 4, 30 * 4), (240, 240, 240))
    for i, (name, (px, vals)) in enumerate(masks.items()):
        tile = Image.new('RGB', (30, 30), (47, 164, 231))
        a = Image.new('L', (px, px))
        a.putdata([min(255, v * 8) for v in vals])
        tile.paste(Image.new('RGB', (px, px), (255, 255, 255)), ((30 - px) // 2, (30 - px) // 2), a)
        sheet.paste(tile.resize((120, 120), Image.NEAREST), (i * 120, 0))
    sheet.save(os.path.join(HERE, 'icons_preview.png'))
    print('wrote', out, total, 'bytes')


if __name__ == '__main__':
    main()
