"""PNG (RGBA) -> C header with a UiImage (ctr64/src/ui/ui.h): up to 255 colours + transparent,
RGB565 palette, alpha 0..32 per entry, run-length coded indices.
usage: png2c.py in.png name out.h [hotspots-json]"""
import json, sys
from PIL import Image

src, name, out = sys.argv[1], sys.argv[2], sys.argv[3]
hot = json.loads(sys.argv[4]) if len(sys.argv) > 4 else None
im = Image.open(src).convert('RGBA')
w, h = im.size
# alpha to 0..32 steps first, so quantisation keeps edges
px = list(im.getdata())
q = Image.new('RGBA', (w, h))
q.putdata([(r, g, b, round(a * 32 / 255) * 255 // 32) if a else (0, 0, 0, 0) for r, g, b, a in px])
pal_im = q.quantize(colors=255, method=Image.Quantize.FASTOCTREE)
idx = list(pal_im.getdata())
pal = pal_im.getpalette()
# per-index colour and alpha from the source pixels mapped to it
acc = {}
for (r, g, b, a), i in zip(q.getdata(), idx):
    s = acc.setdefault(i, [0, 0, 0, 0, 0])
    s[0] += r; s[1] += g; s[2] += b; s[3] += a; s[4] += 1
order = sorted(acc)
remap = {}
palette = [0]
alpha = [0]
for i in order:
    r, g, b, a, n = acc[i]
    a32 = round(a / n * 32 / 255)
    if a32 == 0:
        remap[i] = 0
        continue
    remap[i] = len(palette)
    palette.append(((r // n >> 3) << 11) | ((g // n >> 2) << 5) | (b // n >> 3))
    alpha.append(a32)
data = [remap[i] for i in idx]
# RLE: c < 0x80: c+1 literals follow; c >= 0x80: (c & 0x7F)+1 copies of the next byte
rle = []
i = 0
while i < len(data):
    j = i
    while j < len(data) and j - i < 128 and data[j] == data[i]:
        j += 1
    if j - i >= 3:
        rle += [0x80 | (j - i - 1), data[i]]
        i = j
        continue
    k = i
    lit = []
    while k < len(data) and len(lit) < 128:
        if k + 2 < len(data) and data[k] == data[k + 1] == data[k + 2]:
            break
        lit.append(data[k])
        k += 1
    rle += [len(lit) - 1] + lit
    i = k


def arr(vals, per=24):
    return ',\n'.join('    ' + ', '.join(str(v) for v in vals[n:n + per]) for n in range(0, len(vals), per))


with open(out, 'w', newline='\n') as f:
    f.write(f'/* generated by tools/ui/png2c.py from {src.replace(chr(92), "/").split("/")[-1]}; do not edit */\n')
    f.write('#pragma once\n#include "ui.h"\n\n')
    f.write(f'static const u16 {name}_pal[{len(palette)}] = {{\n{arr(palette, 12)}}};\n')
    f.write(f'static const u8 {name}_alpha[{len(alpha)}] = {{\n{arr(alpha)}}};\n')
    f.write(f'static const u8 {name}_rle[{len(rle)}] = {{\n{arr(rle)}}};\n')
    f.write(f'static const UiImage {name} = {{{w}, {h}, {len(palette)}, {name}_pal, {name}_alpha, {name}_rle}};\n')
    if hot:
        f.write('\ntypedef struct { const char *name; float x, y; s16 r; const char *kind; } PadHot; /* x, y: exact centre in image pixels */\n')
        f.write(f'static const PadHot {name}_hot[{len(hot)}] = {{\n')
        for e in hot:
            f.write(f'    {{"{e["name"]}", {float(e["x"]):.1f}f, {float(e["y"]):.1f}f, {e["r"]}, "{e["kind"]}"}},\n')
        f.write('};\n')
print(f'{w}x{h}, {len(palette)} colours, {len(rle)} bytes RLE')
