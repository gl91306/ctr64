"""Root certificates for box art downloads -> ctr64/src/net_roots.h

    python tools/ui/net_roots.py <cacert.pem> ctr64/src/net_roots.h

cacert.pem: the Mozilla CA list (e.g. Python's certifi). raw.githubusercontent.com chains to
ISRG Root X1 today; the others are kept in case GitHub changes CA.
"""
import re
import sys

WANT = ['ISRG Root X1', 'ISRG Root X2', 'DigiCert Global Root G2', 'DigiCert Global Root CA',
        'USERTrust RSA Certification Authority', 'USERTrust ECC Certification Authority']

src = open(sys.argv[1], encoding='utf8').read()
found = {}
for issuer, pem in re.findall(r'# Issuer: (.*?)\n.*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', src, re.S):
    for w in WANT:
        if 'CN=' + w in issuer and w not in found:
            found[w] = pem
missing = [w for w in WANT if w not in found]
assert not missing, missing

NL = chr(92) + 'n'  # the two characters backslash, n
with open(sys.argv[2], 'w', encoding='utf8', newline='\n') as f:
    f.write('/* Generated by tools/ui/net_roots.py - do not edit. Root certificates for box art downloads\n')
    f.write(' * (raw.githubusercontent.com: ISRG Root X1 today; the others in case GitHub changes CA), from\n')
    f.write(' * the Mozilla CA list. PEM, one string (its terminating NUL counts: mbedTLS wants it). */\n')
    f.write('#pragma once\n\nstatic const char k_net_roots_pem[] =\n')
    for w in WANT:
        f.write('    /* %s */\n' % w)
        for line in found[w].strip().split('\n'):
            f.write('    "%s%s"\n' % (line.strip(), NL))
    f.write('    ;\n')
print('wrote', len(WANT), 'certificates')
