"""Cartridge ID -> libretro-thumbnails box art name, for the game list's top-screen carousel.

    python tools/ui/boxart_names.py <No-Intro N64 .dat> <Named_Boxarts folder> ctr64/src/ui/boxart_names.h

The .dat is libretro-database's metadat/no-intro/"Nintendo - Nintendo 64.dat" (every game with
its 4-character serial, the ID in the ROM header at 0x3B: media, 2-letter game code, region).
The folder is a checkout of github.com/libretro-thumbnails/Nintendo_-_Nintendo_64 (Named_Boxarts).
Only names with art are kept; git symlinks (aliases of other images, checked out on Windows as
small text files holding the target name) are resolved, since GitHub's raw files serve the link
text instead of the image. One name per serial: retail before beta/proto/demo, then the first
release before revisions, then the shortest.
"""
import os
import re
import sys

dat, art_dir, out = sys.argv[1:4]

# names with art -> the file actually holding the image
art = {}
for f in os.listdir(art_dir):
    if not f.endswith('.png'):
        continue
    p = os.path.join(art_dir, f)
    with open(p, 'rb') as fh:
        head = fh.read(300)
    name = f[:-4]
    if head.startswith(b'\x89PNG'):
        art[name] = name
    else:  # symlink text: the target's file name
        target = head.decode('utf8').strip()
        if target.endswith('.png'):
            art[name] = target[:-4]
art = {k: v for k, v in art.items() if os.path.getsize(os.path.join(art_dir, v + '.png')) > 1000}


def thumb(n):  # libretro thumbnail names replace these characters with _
    return re.sub(r'[&*/:`<>?\\|"]', '_', n)


names_by_serial = {}
for m in re.finditer(r'game \(\s*name "([^"]*)".*?\n\)', open(dat, encoding='utf8').read(), re.S):
    block = m.group(0)
    s = re.search(r'serial "([^"]*)"', block)
    if not s or len(s.group(1)) != 4 or not s.group(1).isalnum():
        continue
    names_by_serial.setdefault(s.group(1).upper(), set()).add(m.group(1))


def rank(n):
    lower = n.lower()
    unreleased = any(t in lower for t in ('(beta', '(proto', '(demo', '(kiosk', '(sample', '(debug', '(pirate', '(hack'))
    return (unreleased, '(rev ' in lower, len(n), n)


table = {}
for serial, names in names_by_serial.items():
    with_art = [n for n in names if thumb(n) in art]
    if with_art:
        table[serial] = art[thumb(sorted(with_art, key=rank)[0])]

pool = bytearray()
entries = []
for serial in sorted(table):
    entries.append((serial, len(pool)))
    pool += table[serial].encode('utf8') + b'\0'
assert len(pool) < 65536

with open(out, 'w', encoding='utf8', newline='\n') as f:
    f.write('/* Generated by tools/ui/boxart_names.py - do not edit. Cartridge ID (ROM header 0x3B-0x3E)\n')
    f.write(' * -> libretro-thumbnails Nintendo 64 Named_Boxarts name (without .png). %d games. */\n' % len(entries))
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('static const struct { char id[4]; uint16_t name; } k_boxart_ids[%d] = {\n' % len(entries))
    for s, o in entries:
        f.write('    {{\'%s\', \'%s\', \'%s\', \'%s\'}, %d},\n' % (s[0], s[1], s[2], s[3], o))
    f.write('};\n\nstatic const char k_boxart_pool[%d] =\n' % (len(pool) + 1))
    text = pool.decode('utf8')
    for chunk in text.split('\0')[:-1]:
        esc = chunk.replace('\\', '\\\\').replace('"', '\\"')
        f.write('    "%s\\0"\n' % esc)
    f.write('    ;\n')
print('%d serials with art (of %d), pool %d bytes' % (len(entries), len(names_by_serial), len(pool)))
